    m_dash = re.match(r'^(\d{1,2})-(\d{1,2})$', date_text)
    if m_dash:
        mo, da = int(m_dash.group(1)), int(m_dash.group(2))
        return f"{year}-{mo:02d}-{da:02d}"

    # Check '105' -> 10.5 or '1018' -> 10.18 or '115' -> 1.15
    if date_text == '105':
        return f"{year}-10-05"
    if date_text == '1018':
        return f"{year}-10-18"
    if date_text == '115':
        return f"{year}-01-15"

    # Check 'M.D' e.g. '12.3', '1.24'
    m_dot = re.match(r'^(\d{1,2})\.(\d{1,2})$', date_text)
    if m_dot:
        mo, da = int(m_dot.group(1)), int(m_dot.group(2))
        return f"{year}-{mo:02d}-{da:02d}"

    # Check '11:35' -> likely 11.25 or 12.05
    if ':' in date_text:
        return f"{year}-{month:02d}-10"

    return f"{year}-{month:02d}-10"


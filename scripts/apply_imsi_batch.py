def apply_to_db(db_path):
    print(f"Applying to {db_path}...")
    if not os.path.exists(os.path.dirname(db_path)):
        os.makedirs(os.path.dirname(db_path), exist_ok=True)
    use_store(db_path)
    
    # 1. imsi 건물 생성 또는 업데이트
    b = Building.get("imsi")
    if not b:
        b = Building(id="imsi", name="임시 매장 (401~505호)", aliases=["imsi", "임시"])
    b.name = "임시 매장 (401~505호)"
    b.units = [u["unit"] for u in UNITS_DATA]
    b.save("units_realigned")

    # 2. 기존 가짜/임시 호실 정리 (기존 204, 205, 301호 등 삭제)
    with store().tx(quiet=True):
        Payment.purge("imsi")
        Contract.purge("imsi")
        store().db.execute("DELETE FROM objects WHERE kind='room' AND json_extract(data, '$.building_id') = 'imsi'")
        
        # 3. 신규 10개실 계약 및 호실 등록
        for d in UNITS_DATA:
            u_num = d["unit"]
            b.add_unit(u_num)
            u = b.unit(u_num)
            u.update({
                "name": d["name"],
                "tenant_name": d["name"],
                "id_number": d["id_number"],
                "phone": d["phone"],
                "move_in": d["move_in"],
                "expiry": d["expiry"],
                "deposit": d["deposit"],
                "rent": d["rent"],
                "maintenance": d["maintenance"],
                "clean_fee": d["clean_fee"],
                "pay_timing": d["pay_timing"],
                "lease_type": d["lease_type"]
            })
            
            # 수납 내역 저장
            for m, pinfo in d["payments"].items():
                p_date, r_amt, m_amt, note = pinfo
                is_paid = (r_amt + m_amt) > 0 and bool(p_date)
                Payment(
                    id=Payment.pid("imsi", u_num, 2025, m),
                    building_id="imsi",
                    unit=u_num,
                    year=2025,
                    month=m,
                    paid=is_paid,
                    paid_date=p_date if is_paid else "",
                    rent_amount=r_amt if is_paid else None,
                    maintenance_amount=m_amt if is_paid else None,
                    note=note,
                    tenant_name=d["name"],
                    tenant_id_number=d["id_number"]
                ).save("imsi_batch_synced")

        b.sync_all_rooms()
        Building.invalidate_cache()
    print(f"Successfully populated {len(UNITS_DATA)} units in {db_path}!")

# 컨테이너 내 가능한 모든 DB 위치에 일괄 적용
target_dbs = ["/media/rent2.db", "/app/apps/rent2/data/rent2.db", "/app/integrat.db"]
for path in target_dbs:
    try:
        apply_to_db(path)
    except Exception as e:
        print(f"Error on {path}: {e}")

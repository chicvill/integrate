"""
scripts/build_rent_bundle.py
Build standalone bundle.js for apps/rent from frontend modules,
and sync frontend files with apps/rent root for maximum compatibility.
"""
import os
import re
import shutil

RENT_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "apps", "rent"))
FRONTEND_DIR = os.path.join(RENT_DIR, "frontend")

def strip_es_syntax(code: str) -> str:
    # 1. Strip multi-line and single-line import statements
    code = re.sub(r'import\s+[\s\S]*?from\s+[\'"][^\'"]+[\'"];?', '', code)
    # 2. Strip bare imports e.g. import './something.js';
    code = re.sub(r'import\s+[\'"][^\'"]+[\'"];?', '', code)

    lines = []
    for line in code.splitlines():
        # Replace export default / export const / export async function / export function
        line = re.sub(r'^\s*export\s+default\s+', '', line)
        line = re.sub(r'^\s*export\s+(const|let|var|async\s+function|function|class)\s+', r'\1 ', line)
        # Remove export { ... }
        if re.match(r'^\s*export\s*\{', line):
            continue
        lines.append(line)
    return "\n".join(lines)

def build_bundle():
    state_code = open(os.path.join(FRONTEND_DIR, "js", "state.js"), "r", encoding="utf-8").read()
    api_code = open(os.path.join(FRONTEND_DIR, "js", "api.js"), "r", encoding="utf-8").read()
    ui_code = open(os.path.join(FRONTEND_DIR, "js", "ui.js"), "r", encoding="utf-8").read()
    slider_code = open(os.path.join(FRONTEND_DIR, "js", "slider.js"), "r", encoding="utf-8").read()
    modals_code = open(os.path.join(FRONTEND_DIR, "js", "modals.js"), "r", encoding="utf-8").read()
    app_code = open(os.path.join(FRONTEND_DIR, "app.js"), "r", encoding="utf-8").read()

    combined = [
        "/**",
        " * apps/rent/frontend/bundle.js",
        " * Standalone bundle supporting both file:/// and http:// protocols.",
        " * Generated by scripts/build_rent_bundle.py",
        " */",
        "(function() {",
        strip_es_syntax(api_code),
        strip_es_syntax(state_code),
        strip_es_syntax(ui_code),
        strip_es_syntax(slider_code),
        strip_es_syntax(modals_code),
        strip_es_syntax(app_code),
        "})();"
    ]

    bundle_content = "\n\n".join(combined)
    bundle_path = os.path.join(FRONTEND_DIR, "bundle.js")
    with open(bundle_path, "w", encoding="utf-8") as f:
        f.write(bundle_content)
    print(f"Generated {bundle_path} ({len(bundle_content)} bytes)")

    # Sync to apps/rent root
    sync_files = ["bundle.js", "index.html", "branches.html", "app.js", "manual.html"]
    for fname in sync_files:
        src = os.path.join(FRONTEND_DIR, fname)
        dst = os.path.join(RENT_DIR, fname)
        if os.path.exists(src):
            shutil.copy2(src, dst)
            print(f"Synced {fname} -> apps/rent/{fname}")

    # Also sync js/ directory
    src_js = os.path.join(FRONTEND_DIR, "js")
    dst_js = os.path.join(RENT_DIR, "js")
    if os.path.exists(src_js):
        for jf in os.listdir(src_js):
            shutil.copy2(os.path.join(src_js, jf), os.path.join(dst_js, jf))
            print(f"Synced js/{jf} -> apps/rent/js/{jf}")

if __name__ == "__main__":
    build_bundle()

def split_rent_maint(total_amount):
    """
    사용자 정의 분리 규칙:
    - 440,000원 -> 임차료 290,000원 + 관리비 150,000원
    - 450,000원 -> 임차료 290,000원 + 관리비 160,000원
    - 390,000원 -> 임차료 240,000원 + 관리비 150,000원
    - 540,000원 -> 임차료 390,000원 + 관리비 150,000원
    - 150,000원 -> 임차료 0원 + 관리비 150,000원
    - 250,000원 -> 임차료 200,000원 + 관리비 50,000원
    - 400,000원 -> 임차료 250,000원 + 관리비 150,000원
    - 500,000원 -> 임차료 350,000원 + 관리비 150,000원
    - 44,000원  -> 임차료 29,000원 + 관리비 15,000원
    - 그 외     -> 관리비 150,000원 기준 차액 배분 (또는 0, total)
    """
    if total_amount == 440000:
        return 290000, 150000
    elif total_amount == 450000:
        return 290000, 160000
    elif total_amount == 390000:
        return 240000, 150000
    elif total_amount == 540000:
        return 390000, 150000
    elif total_amount == 150000:
        return 0, 150000
    elif total_amount == 250000:
        return 200000, 50000
    elif total_amount == 400000:
        return 250000, 150000
    elif total_amount == 500000:
        return 350000, 150000
    elif total_amount == 44000:
        return 29000, 15000
    elif total_amount == 0:
        return 0, 0
    elif total_amount > 150000:
        return total_amount - 150000, 150000
    else:
        return total_amount, 0

def parse_date_str(raw, expected_year, expected_month):
    raw = raw.strip()
    if not raw or "전출" in raw or "전입" in raw or "주인" in raw:
        return None, raw
    
    # 2026-1-29
    m = re.match(r"^(\d{4})[-.](\d{1,2})[-.](\d{1,2})$", raw)
    if m:
        return f"{m.group(1)}-{int(m.group(2)):02d}-{int(m.group(3)):02d}", ""
    
    # 12. 3 or 12.21 or 12-21 or 12/21
    m = re.match(r"^(\d{1,2})[.\-:/ ]+(\d{1,2})$", raw)
    if m:
        m_val, d_val = int(m.group(1)), int(m.group(2))
        return f"{expected_year}-{m_val:02d}-{d_val:02d}", ""
    
    # 115 -> 1.15 / 105 -> 10.5
    if raw.isdigit():
        if len(raw) == 3:
            if expected_month == 1:
                return f"{expected_year}-01-{int(raw[1:]):02d}", ""
            elif expected_month == 10:
                return f"{expected_year}-10-0{raw[2]}", ""
        elif len(raw) == 4:
            return f"{expected_year}-{int(raw[:2]):02d}-{int(raw[2:]):02d}", ""

    return None, raw

def parse_amt_str(raw):
    raw = raw.strip()
    digits = re.sub(r"[^\d]", "", raw)
    if digits:
        return int(digits)
    return 0

